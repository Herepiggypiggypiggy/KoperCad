#!/usr/bin/env python3
"""Writes THIRD_PARTY_NOTICES.txt: the licences of the Rust crates in the Windows build.

Usage (from the repository root, needs cargo and Python 3, no admin rights):

    python tools/third-party-notices.py            # rewrite THIRD_PARTY_NOTICES.txt
    python tools/third-party-notices.py --check    # exit 1 if the file is out of date

Which crates: the normal (non-dev, non-build) dependencies of novo-app and
novo-cli for x86_64-pc-windows-msvc, from Cargo.lock. Crates fetched once
(`cargo fetch --locked`) are read from the local cargo registry, so the script
works offline afterwards. Each crate's own licence files are copied, grouped by
identical text. Things that are not Rust crates (fonts, SQLite) are in the
fixed header below.
"""
import hashlib
import json
import pathlib
import subprocess
import sys

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "THIRD_PARTY_NOTICES.txt"
LICENSE_PREFIXES = ("license", "licence", "copying", "unlicense", "notice", "copyright")

HEADER = """\
KoperCAD third-party notices
============================

KoperCAD is made by KoperVonk. It contains and links the software below. Each
part keeps its own licence; the full texts follow the lists. KoperCAD's own
terms are not covered by this file.

This file is generated by tools/third-party-notices.py from Cargo.lock. Do not
edit it by hand.

A crate marked "no licence file shipped" publishes no licence text in its
package; the licence named after it applies, and its standard text (MIT or
Apache-2.0) is among the texts below. Its copyright belongs to the authors
named at the repository link.

Not Rust crates
---------------

* Inter (fonts, subset, bundled in the program and used in PDF export):
  SIL Open Font License 1.1, copyright The Inter Project Authors
  (https://github.com/rsms/inter). Full text: under "Licence texts" (Inter fonts).
* SQLite (project file engine, built into the program by the libsqlite3-sys
  crate): public domain (https://sqlite.org/copyright.html).
* The default fonts of the egui toolkit (Hack, Ubuntu-Light, NotoEmoji and
  emoji-icon-font, bundled by the epaint crate) are listed with that crate
  below: OFL 1.1, Ubuntu Font Licence 1.0, MIT and Apache-2.0.
* The KoperCAD mark and symbol library are KoperVonk's own work. No EPLAN,
  customer or maker data is bundled.
"""


def run(*args):
    return subprocess.run(args, cwd=ROOT, check=True, capture_output=True, text=True).stdout


def main():
    meta = json.loads(run("cargo", "metadata", "--format-version", "1", "--locked"))
    tree = run(
        "cargo", "tree", "--locked", "--target", "x86_64-pc-windows-msvc",
        "-e", "normal", "--prefix", "none", "--format", "{p}",
        "-p", "novo-app", "-p", "novo-cli",
    )
    wanted = set()
    for line in tree.splitlines():
        parts = line.split()
        if len(parts) >= 2 and parts[1].startswith("v"):
            wanted.add((parts[0], parts[1][1:]))
    crates = []
    for p in meta["packages"]:
        if p["source"] is None or (p["name"], p["version"]) not in wanted:
            continue  # workspace crates (KoperCAD itself) and crates not in the build
        crates.append(p)
    crates.sort(key=lambda p: (p["name"], p["version"]))

    texts = {}  # hash -> (text, [crate labels])
    lines = []
    for p in crates:
        label = f'{p["name"]} {p["version"]}'
        src = pathlib.Path(p["manifest_path"]).parent
        files = sorted(
            f for f in src.iterdir()
            if f.is_file() and f.name.lower().startswith(LICENSE_PREFIXES)
        )
        for f in files:
            text = f.read_bytes().decode("utf-8", "replace").strip().replace("\r\n", "\n")
            if not text:
                continue
            h = hashlib.sha256(text.encode()).hexdigest()
            texts.setdefault(h, (text, []))[1].append(label)
        note = "" if files else "  (no licence file shipped in the crate; see its repository)"
        lines.append(f'* {label}: {p["license"] or "see repository"}'
                     f'  {p["repository"] or ""}{note}'.rstrip())

    out = [HEADER, f"Rust crates ({len(crates)})", "-" * 18, ""]
    out += lines
    out += ["", "", "Licence texts", "-------------", ""]
    inter = (ROOT / "crates/novo-theme/assets/fonts/Inter-LICENSE.txt").read_text(encoding="utf-8").strip()
    texts[hashlib.sha256(inter.encode()).hexdigest()] = (inter, ["Inter fonts"])
    for i, (text, labels) in enumerate(sorted(texts.values(), key=lambda t: t[1][0]), 1):
        out.append("=" * 78)
        out.append(f"Text {i}, shipped with: " + ", ".join(sorted(set(labels))))
        out.append("=" * 78)
        out.append(text)
        out.append("")
    result = "\n".join(out) + "\n"

    if "--check" in sys.argv:
        if not OUT.exists() or OUT.read_text(encoding="utf-8") != result:
            print("THIRD_PARTY_NOTICES.txt is out of date; run tools/third-party-notices.py")
            sys.exit(1)
        return
    OUT.write_text(result, encoding="utf-8", newline="\n")
    print(f"wrote {OUT.name}: {len(crates)} crates, {len(texts)} licence texts, {len(result)//1024} KiB")


main()
